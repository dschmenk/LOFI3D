;*
;**************************************

	JMP	INIT
	
	.BYTE	"COPYRIGHT 2007, DAVID SCHMENK"

INIT:	LDX	#$00
	LDA	MAPSTRD
	BNE	WID2SFT
	RTS		;CAN'T HAVE ZERO WIDTH MAP
WID2SFT:	INX
	LSR
	BNE	WID2SFT
	DEX
	STX	MAPSHFT
	LDA	#$01	;ENABLE JOYSTICK BY DEFAULT
	STA	JOYSTICK
.IFDEF VBLTIMER
	JSR	VBLINIT	;INIT VBL IF POSSIBLE
.ENDIF
	LDX	#$00
SAVEMEM:	LDA	$00,X
	STA	ZPIMG,X
	LDA	$800,X
	STA	TXT2IMG,X
	LDA	$800+256,X
	STA	TXT2IMG+256,X
	LDA	$800+512,X
	STA	TXT2IMG+512,X
	LDA	$800+768,X
	STA	TXT2IMG+768,X
	INX
	BNE	SAVEMEM
	LDA	COLORFLOOR
	STA	CLRFLR
	LDA	COLORCEILING
	STA	CLRCEIL
	LDA	DISPPG1	;FIRST PAGE
	LDA	DISPMIX	;FULL SCREEN MODE/NO MIX
	LDA	GRLORES	;LORES GRAPHICS MODE
	LDA	DISPGR	;GRAPHICS MODE
	LDX	#$01
	STX	RENDERSTATUS
	DEX
	STX	RENDERPAGE
	STX	DEMOFPS
	JSR	STATUSINIT
	JSR	MAPUPDT	;INIT MAP PTRS
	JSR	GCINIT	;INIT GAMECONTROLLERS
	LDA	CNTRX
	CMP	#56
	BCC	DEMOLOOP
	LDA	CNTRY
	CMP	#56
	BCC	DEMOLOOP
	LDA	#$00
	STA	JOYSTICK
	LDA	#32
	STA	CNTRX
	STA	CNTRY
;
; MAIN LOOP
;
DEMOLOOP:	LDA	CNTRX
	STA	GCXPOS
	LDA	CNTRY
	STA	GCYPOS
	LDA	JOYSTICK
	BEQ	CHKKB
	JSR	GCREAD
	LDA	#$00
	STA	TONE
	LDA	GCBTTNS
	BNE	OPENDOOR
CHKKB:	LDA	KBHIT
	BMI	KEYPRESS
UPDATE:	JSR	PLAYER
;	JSR	ACTORS
	LDA	RENDERPAGE	;UPDATE RENDER BUFFER
	EOR	#$01
	STA	RENDERPAGE
	JSR	RENDER
	LDX	RENDERPAGE
	LDA	DISPPAGE,X	;DISPLAY NEW BUFFER
	INC	DEMOFPS
	LDA	VBLCNT
	CMP	#60
	BCC	DEMOLOOP
	LDA	#$00
	STA	VBLCNT	
	LDA	RENDERSTATUS
	BEQ	DEMOLOOP
	JSR	STATUSUPDT
	JMP	DEMOLOOP
;
; KEYPRESS HANDLER
;
KEYPRESS:	STA	KBSTROBE
	CMP	#$A0	;SPACEBAR
	BEQ	OPENDOOR
	CMP	#$C1	;'A' KEY
	BEQ	MVFORWARD
	CMP	#$8B	;UP ARROW
	BEQ	MVFORWARD
	CMP	#$DA	;'Z' KEY
	BEQ	MVBACKWRD
	CMP	#$8A	;DOWN ARROW
	BEQ	MVBACKWRD
	CMP	#$88	;LEFT ARROW
	BEQ	TURNLT
	CMP	#$95	;RIGHT ARROW
	BEQ	TURNRT
	CMP	#$D0	;'P' KEY
	BNE	KEYCHKJ
	JMP	TOGGLESTATUS
KEYCHKJ:	CMP	#$CA	;'J' KEY
	BNE	KEYCHKESC
	JMP	TOGGLEJOYSTK
KEYCHKESC:	CMP	#$9B	;ESC KEY
	BNE	KBEXIT
	JMP	ESCEXIT
KBEXIT:	JMP	UPDATE
;
; OPEN DOOR IN MAP
;
OPENDOOR:	LDA	AHEADDST+1
	CMP	#$02
	BCS	CHKKB	;TOO FAR AWAY
	LDA	AHEADOBJ
	CMP	#$E0	;LOOK FOR DOOR
	BEQ	OPENIT
	CMP	#$0E
	BEQ	OPENIT
	CMP	#$F0	;LOOK FOR EXIT
	BEQ	EXITDOOR
	CMP	#$0F
	BEQ	EXITDOOR
	JMP	CHKKB	;NOT DOOR
OPENIT:	LDY	AHEADX+1
	LDX	AHEADPTR
	STX	MAPPTR
	LDX	AHEADPTR+1
	STX	MAPPTR+1
	EOR	(MAPPTR),Y
	STA	(MAPPTR),Y
	LDA	#$08
	STA	TONE
	JMP	CHKKB
EXITDOOR:	LDA	#$00
;
; KEYBOARD MOVEMENT
;
MVFORWARD:	LDA	CNTRY
	LSR
	LSR
	STA	GCYPOS
	JMP	UPDATE
MVBACKWRD:	LDA	CNTRY
	ASL
	STA	GCYPOS
	JMP	UPDATE
TURNLT:	LDA	CNTRX
	SEC
	SBC	#16+2
	STA	GCXPOS
	JMP	UPDATE
TURNRT:	LDA	CNTRX
	CLC
	ADC	#16-2
	STA	GCXPOS
	JMP	UPDATE
;
; TOGGLE JOYSTICK INPUT
;
TOGGLEJOYSTK:	LDA	JOYSTICK
	BNE	TOGGLEJOYOFF
	JSR	GCINIT	;INIT GAMECONTROLLERS
	LDA	CNTRX
	CMP	#56
	BCC	TOGGLEJOYON
	LDA	CNTRY
	CMP	#56
	BCC	TOGGLEJOYON
TOGGLEJOYOFF:	LDA	#$00
	STA	JOYSTICK
	LDA	#32
	STA	CNTRX
	STA	CNTRY
	JMP	UPDATE
TOGGLEJOYON:	LDA	#$01
	STA	JOYSTICK
	JMP	UPDATE
;
; TOGGLE STATUS PANEL
;
TOGGLESTATUS:	LDA	RENDERSTATUS
	EOR	#$01
	STA	RENDERSTATUS
	TAX
	STA	DISPSPLIT,X
	BEQ	TOGGLESTATOFF
	JSR	STATUSINIT
	JMP	UPDATE
TOGGLESTATOFF:	LDA	#0
	STA	VIEWCOLLEFT
	LDA	#40
	STA	VIEWCOLRIGHT
	JMP	UPDATE
;
; ESCAPE BACK TO BASIC
;
ESCEXIT:	STA	DISPPG1
	STA	DISPTXT
	JMP	RETURN
;
; STATUS DISPLAY
;
STATUSINIT:	LDA	#4
	STA	VIEWCOLLEFT
	LDA	#36
	STA	VIEWCOLRIGHT
	LDA	#$A0
	LDX	#40
STATUSCLEAR:	DEX
	LDA	#$00
	STA	$400,X
	STA	$800,X
	STA	$480,X
	STA	$880,X
	STA	$500,X
	STA	$900,X
	STA	$580,X
	STA	$980,X
	STA	$600,X
	STA	$A00,X
	STA	$680,X
	STA	$A80,X
	STA	$700,X
	STA	$B00,X
	STA	$780,X
	STA	$B80,X
	STA	$428,X
	STA	$828,X
	STA	$4A8,X
	STA	$8A8,X
	STA	$528,X
	STA	$928,X
	STA	$5A8,X
	STA	$9A8,X
	STA	$628,X
	STA	$A28,X
	STA	$6A8,X
	STA	$AA8,X
	STA	$728,X
	STA	$B28,X
	STA	$7A8,X
	STA	$BA8,X
	STA	$450,X
	STA	$850,X
	STA	$4D0,X
	STA	$8D0,X
	STA	$550,X
	STA	$950,X
	STA	$5D0,X
	STA	$9D0,X
	LDA	#$A0
	STA	$650,X
	STA	$A50,X
	STA	$6D0,X
	STA	$AD0,X
	STA	$750,X
	STA	$B50,X
	STA	$7D0,X
	STA	$BD0,X
	CPX	#$00
	BEQ	STATUSTXT
	JMP	STATUSCLEAR
STATUSTXT:	LDA	STATUSTXT1,X
	BEQ	STATUSDONE
	ORA	#$80
	STA	$6D0+8,X
	STA	$AD0+8,X
	LDA	STATUSTXT2,X
	ORA	#$80
	STA	$750+8,X
	STA	$B50+8,X
.IFDEF VBLTIMER
	LDA	STATUSFPS,X
	ORA	#$80
	STA	$750+33,X
	STA	$B50+33,X
.ENDIF
	INX
	BNE	STATUSTXT
.IFDEF VBLTIMER
STATUSUPDT:	LDA	DEMOFPS
	LDY	#$00
STATUSDIV10:	CMP	#10
	BCC	STATUSFPS
	INY
	SEC
	SBC	#10
	BPL	STATUSDIV10
STATUSFPS:	LDX	DIGIT,Y
	STX	$750+38
	STX	$B50+38
	TAY
	LDA	DIGIT,Y
	STA	$750+39
	STA	$B50+39
STATUSDONE:	LDA	#$00
	STA	DEMOFPS
.ELSE
STATUSUPDT:
STATUSDONE:
.ENDIF
	RTS
;
; RETURN BACK TO BASIC AFTER RESTORING ZP AND TXTPG2
;
RETURN:	STA	RETCODE
	LDX	#$00
RESTOREMEM:	LDA	ZPIMG,X
	STA	$00,X
	LDA	TXT2IMG,X
	STA	$800,X
	LDA	TXT2IMG+256,X
	STA	$800+256,X
	LDA	TXT2IMG+512,X
	STA	$800+512,X
	LDA	TXT2IMG+768,X
	STA	$800+768,X
	INX
	BNE	RESTOREMEM
.IFDEF VBLTIMER
	JMP	VBLCLEAR
;
; VBL INTERRUPT TIMER
;
INTPARM:	.BYTE	2
	.BYTE	0
	.ADDR	VBLINT
VBLINIT:	LDA	#$00
	STA	VBLCNT
	STA	VBLCNT+1
	LDA	$C4FB
	CMP	#$D6	;MOUSE ID BYTE
	BEQ	INSTALLINT
	CMP	#$01	;ON MY IIC+, THIS IS 01
	BEQ	INSTALLINT
	RTS
INSTALLINT:	LDA	$BF00
	CMP	#$4C	;LOOK FOR JMP INSTRUCTION
	BNE	INSTALLDOS33
	JSR	$BF00	;PRODOS INSTALL INT
	.BYTE	$40
	.ADDR	INTPARM
	JMP	SETVECS
INSTALLDOS33:	LDA	$03FE
	STA	PREVINT
	LDA	$03FF
	STA	PREVINT+1
	LDA	#<DOSVBLINT
	STA	$03FE
	LDA	#>DOSVBLINT
	STA	$03FF
SETVECS:	LDA	$C412									;LSB OF SETMOUSE ROUTINE
	STA	SETMOUSE+1
	LDA	$C413										;LSB OF SERVEMOUSE ROUTINE
	STA	SERVEMOUSE+1
	LDA	$FBB3										;NOP SERVEMOUSE FOR MY IIC
	CMP	#$06											; IT DOESN'T SEEM TO WORK
	BNE	NOTIIC
	LDA	$FBC0
	BNE	NOTIIC
	LDA	#$EA
	STA	SERVEMOUSE
	STA	SERVEMOUSE+1
	LDA	#$18
	STA	SERVEMOUSE+2
NOTIIC:	LDA	#$08											;DISABLE MOUSE, ENABLE VLB INT
SETMOUSE:	JSR	$C400
	RTS
VBLCLEAR:	LDA	$C4FB
	CMP	#$D6	;MOUSE ID BYTE
	BEQ	REMOVEINT
	CMP	#$01	;ON MY IIC+, THIS IS 01
	BNE	VBLEXIT
REMOVEINT:	LDA	$BF00
	CMP	#$4C	;LOOK FOR JMP INSTRUCTION
	BNE	REMOVEDOS33
	LDA	#$00
	JSR	SETMOUSE
	LDA	#$01
	STA	INTPARM
	JSR	$BF00	;PRODOS UNINSTALL INT
	.BYTE	$41
	.ADDR	INTPARM
	RTS
REMOVEDOS33:	LDA	#$00
	JSR	SETMOUSE
	LDA	PREVINT
	STA	$03FE
	LDA	PREVINT+1
	STA	$03FF
	RTS
;
; INTERRUPT ROUTINE
;
DOSVBLINT:	PHP
	PHA
	TXA
	PHA
	TYA
	PHA
	JSR	VBLINT
	PLA
	TAY
	PLA
	TXA
	PLA
	PLP
	RTI
VBLINT:	CLD
SERVEMOUSE:	JSR	$C400
	BCS	VBLEXIT
;
; INCREMENT 16 BIT COUNTER
;
	LDA	VBLCNT
	ADC	#$01
	STA	VBLCNT
	LDA	VBLCNT+1
	ADC	#$00
	STA	VBLCNT+1
	CLC
.ENDIF
VBLEXIT:	RTS
	.DATA

STATUSTXT1:	.BYTE	"PRESS 'P' TO TOGGLE PANEL", 0
STATUSTXT2:	.BYTE	"PRESS 'ESC' TO QUIT DEMO ", 0
STATUSFPS:	.BYTE	"FPS:                                    ", 0;
DIGIT:	.BYTE	'0'|$80, '1'|$80, '2'|$80, '3'|$80, '4'|$80
	.BYTE	'5'|$80, '6'|$80, '7'|$80, '8'|$80, '9'|$80

	.BSS

PREVINT:	.RES	2
DEMOFPS:	.RES	1
VBLCNT:	.RES	2	
ZPIMG:	.RES	256
TXT2IMG:	.RES	1024