	STA	PREVY+1	;PREVY = INCY
	ADC	#$00
	STA	INCY+1
	JMP	XPYPCHKY
XPYPHITOBJY:	CPY	RAYX+1
	BEQ	XPYPCHKWALLY
	JSR	XPYPADDOBJY
	BCC	XPYPCHKWALLY
XPYPHITOBJX:	CPY	RAYX+1
	BEQ	XPYPCHKWALLX
	JSR	XPYPADDOBJX
	BCC	XPYPCHKWALLX
XPYPHITY:	STA	HITOBJ	;HIT HORIZ WALL
	LDA	#$00
	STA	HITY	;HITY = INT(INCY)
	LDA	INCY+1
	STA	HITY+1
	LDA	INCY	;HITX = 1-FRAC(INCY)/DY+INT(PREVX)
	LDX	DY
	JSR	DIVP8
	EOR	#$FF
	STA	HITX
	SEC
	SBC	RAYX
	TAX
	TYA		;Y=PREVXH
	STA	HITX+1
	SBC	RAYX+1
	JMP	CALCDISTSCALE
XPYPHITX:	STA	HITOBJ	;HIT VERT WALL
	LDA	INCY
	STA	HITY	;HITY = INCY
	LDA	INCY+1
	STA	HITY+1
