	.IMPORT	RAYCAST
	.IMPORT	TEXPAGEUPDT
	.IMPORT	RENDERSTATUS
	.IMPORT	SFXPLAY, SFXUPDT
	.IMPORT	FPS, PREVBTTNS
	.IMPORT	OBJDBTYPE, OBJDBXPOS, OBJDBYPOS, OBJSTATE
