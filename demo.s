	.INCLUDE	"global.inc"
	.IMPORT	PLAYER
	.IMPORT	MAPUPDT
	.IMPORT	GCINIT, GCREAD
	.IMPORT	RENDER

	.CODE

;**************************************
;*
;* THIS IS A TECHNOLOGY DEMONSTRATION
;* 
