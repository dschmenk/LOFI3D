XPYPCHKWALLY:	LDA	OBJPTR	;UPDATE OBJPTR
	CLC
	ADC	MAPWDTH
	STA	OBJPTR
	LDA	OBJPTR+1
	ADC	#$00
	STA	OBJPTR+1
	LDA	MAPPTR	;UPDATE MAPPTR
	CLC
	ADC	MAPWDTH
	STA	MAPPTR
	LDA	MAPPTR+1
	ADC	#$00
	STA	MAPPTR+1
	LDA	(MAPPTR),Y
	AND	#$F0
	BNE	XPYPHITY
XPYPCHKX:	LDA	(OBJPTR),Y
	BNE	XPYPHITOBJX
XPYPCHKWALLX:	INY		;INC X COORD
